-- 0033_finance_payments.sql
-- Money going out: the ledger, and what it means for a request.
--
-- The sheet this replaces keeps four columns on the request row -- Paid Total,
-- Remaining, Status and Last Payment Date -- because a sheet cannot join. They
-- are a cache of payments that do not exist anywhere as rows, and the cost is
-- steep: two part-payments collapse into one total and one date, so the cash
-- flow treats both as having happened on the later day, and the forecast is
-- wrong for every day in between.
--
-- Here each payment is a row. The total is a sum, the status is derived from
-- it, and the dates are real.

CREATE TABLE fin_payments (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id    uuid NOT NULL REFERENCES fin_requests(id) ON DELETE RESTRICT,

  amount        numeric(14,2) NOT NULL,
  paid_at       timestamptz NOT NULL DEFAULT now(),

  -- Free text, for a transfer reference or a cheque number.
  reference     text,
  note          text,

  recorded_by_id uuid NOT NULL REFERENCES core_users(id),
  receipt_file_id uuid REFERENCES fin_request_files(id),

  /*
   * The guard against paying twice.
   *
   * Generated by the browser for each attempt at a payment, so a double click,
   * a retried request after a timeout, or a refresh of a submitted form all
   * carry the same key and collide here. The legacy app has no equivalent: its
   * script lock stops two payments being written at the same instant, which is
   * a different problem from the same payment being written twice in a row.
   */
  idempotency_key text NOT NULL UNIQUE,

  created_at    timestamptz NOT NULL DEFAULT now(),

  -- A reversal is a negative row, never a deletion: the ledger is append-only
  -- so that what was recorded, and when, stays answerable.
  reversal_of_id uuid REFERENCES fin_payments(id),

  CONSTRAINT fin_payments_amount_not_zero CHECK (amount <> 0),
  -- Only a reversal may be negative, and it must say what it reverses.
  CONSTRAINT fin_payments_negative_is_reversal CHECK (
    amount > 0 OR reversal_of_id IS NOT NULL
  )
);

-- The sum, per request. Every read of "how much has been paid" goes through
-- this, so it is the one index that matters here.
CREATE INDEX fin_payments_request_idx ON fin_payments (request_id, paid_at);

-- The cash-flow report asks for payments in a date range.
CREATE INDEX fin_payments_paid_at_idx ON fin_payments (paid_at);

-- One reversal per payment: reversing the same payment twice would credit it
-- back twice, and the second is always a mistake.
CREATE UNIQUE INDEX fin_payments_one_reversal
  ON fin_payments (reversal_of_id) WHERE reversal_of_id IS NOT NULL;

/* -------------------------------------------------- the derived status -- */
-- payment_state exists on fin_requests already and has been UNPAID for
-- everything. From here it is maintained from the ledger, by trigger, so it
-- cannot drift from the rows it describes -- which is exactly what the sheet's
-- four cached columns do.

CREATE OR REPLACE FUNCTION fin_sync_payment_state() RETURNS trigger AS $$
DECLARE
  target uuid := COALESCE(NEW.request_id, OLD.request_id);
  paid numeric(14,2);
  asked numeric(14,2);
BEGIN
  SELECT COALESCE(sum(amount), 0) INTO paid
    FROM fin_payments WHERE request_id = target;
  SELECT requested_amount INTO asked
    FROM fin_requests WHERE id = target;

  UPDATE fin_requests SET payment_state = CASE
    WHEN paid <= 0 THEN 'UNPAID'
    -- Paid in full, or more than asked: both are "done", and the second is a
    -- real thing that happens when a supplier is paid a rounded figure.
    WHEN asked IS NOT NULL AND paid >= asked THEN 'PAID'
    ELSE 'PARTIAL'
  END WHERE id = target;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER fin_payments_sync_state
  AFTER INSERT OR UPDATE OR DELETE ON fin_payments
  FOR EACH ROW EXECUTE FUNCTION fin_sync_payment_state();

-- Changing the amount of a request changes whether it is fully paid, so the
-- same recalculation runs when the figure moves -- an approved edit that
-- raises the amount turns a PAID request back into a PARTIAL one.
CREATE OR REPLACE FUNCTION fin_sync_payment_state_on_request() RETURNS trigger AS $$
DECLARE
  paid numeric(14,2);
BEGIN
  SELECT COALESCE(sum(amount), 0) INTO paid
    FROM fin_payments WHERE request_id = NEW.id;

  NEW.payment_state := CASE
    WHEN paid <= 0 THEN 'UNPAID'
    WHEN NEW.requested_amount IS NOT NULL AND paid >= NEW.requested_amount THEN 'PAID'
    ELSE 'PARTIAL'
  END;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER fin_requests_sync_payment_state
  BEFORE UPDATE OF requested_amount ON fin_requests
  FOR EACH ROW EXECUTE FUNCTION fin_sync_payment_state_on_request();